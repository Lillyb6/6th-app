insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('cloud-photos', 'cloud-photos', false, 5000000, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = 5000000,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

drop policy if exists "Members can read cloud photos" on storage.objects;
create policy "Members can read cloud photos"
  on storage.objects for select to authenticated using (bucket_id = 'cloud-photos');
drop policy if exists "Members can upload their cloud photos" on storage.objects;
create policy "Members can upload their cloud photos"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'cloud-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Members can update their cloud photos" on storage.objects;
create policy "Members can update their cloud photos"
  on storage.objects for update to authenticated
  using (bucket_id = 'cloud-photos' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'cloud-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Members can delete their cloud photos" on storage.objects;
create policy "Members can delete their cloud photos"
  on storage.objects for delete to authenticated
  using (bucket_id = 'cloud-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);
