-- Photos are private and served to signed-in members using short-lived URLs.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Cloud watcher' check (char_length(name) between 1 and 60),
  bio text not null default '' check (char_length(bio) <= 160),
  avatar_path text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  image_path text not null,
  caption text not null check (char_length(caption) between 1 and 500),
  location text not null default '' check (char_length(location) <= 80),
  best boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
);

create index if not exists posts_id_desc_idx on public.posts (id desc);
create index if not exists posts_user_id_id_desc_idx on public.posts (user_id, id desc);
create index if not exists likes_post_id_idx on public.likes (post_id);

create or replace function public.create_cloud_club_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1), 'Cloud watcher')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_cloud_club on auth.users;
create trigger on_auth_user_created_cloud_club
  after insert on auth.users
  for each row execute procedure public.create_cloud_club_profile();

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.likes enable row level security;

drop policy if exists "Signed-in members can read profiles" on public.profiles;
create policy "Signed-in members can read profiles"
  on public.profiles for select to authenticated using (true);
drop policy if exists "Members can create their profile" on public.profiles;
create policy "Members can create their profile"
  on public.profiles for insert to authenticated with check (id = (select auth.uid()));
drop policy if exists "Members can update their profile" on public.profiles;
create policy "Members can update their profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

